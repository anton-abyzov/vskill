#!/usr/bin/env bash
# release-desktop.sh — one-command desktop release (macOS + Windows + Linux)
#
# Usage:
#   bash scripts/release/release-desktop.sh [<version>] [--dry-run] [--rotate-secrets] [--force]
#
#   <version>         X.Y.Z (or X.Y.Z-rcN). Default: the patch after the newest
#                     desktop-v* tag on GitHub. Must be newer than that tag.
#   --dry-run         Preflight, print the plan, read the live manifest and verify
#                     its macOS bundle signature. No tag, push, secret or release
#                     change.
#   --rotate-secrets  Re-upload TAURI_SIGNING_PRIVATE_KEY + _PASSWORD from
#                     KEY_DIR before tagging. The only path that runs gh secret set.
#   --force           Tag even when the newest main run of the desktop nightly
#                     or Sidecar Smoke is red.
#
# Steps:
#   1. Preflight, no side effects: tools, gh auth, key files, rsign sign +
#      verify through a pty, tauri.conf.json pubkey == base64(minisign.pub) at
#      the commit being tagged, required secret names (names only), newest
#      main runs of notarize-dryrun.yml (and its newest full run: push runs
#      skip macOS) and sidecar-smoke.yml green.
#   2. --rotate-secrets only: gh secret set the updater key + passphrase.
#   3. Tag main's HEAD on GitHub as desktop-v<version> and push the tag over
#      HTTPS. No bump commit or PR: desktop-release.yml stamps Cargo.toml,
#      tauri.conf.json and Cargo.lock from the tag, and refuses a tag that is
#      not on main.
#   4. Find the Desktop Release run for the tag and watch it (--exit-status).
#   5. Check the GitHub release carries every bundle and updater .sig.
#   6. Read https://verified-skill.com/desktop/latest.json back: version
#      <version>, served from R2 (x-manifest-source: r2), all three platforms.
#   7. Download the darwin-aarch64 bundle the manifest points at and verify its
#      updater signature with rsign against minisign.pub.
#   8. Promote the release if it is still a draft; delete stale desktop-v*
#      drafts (their git tags are kept).
#
# Why this keypair: v1.0.13..v1.0.27 used keys from BSD `minisign`, which the
# Rust minisign crate inside tauri-bundler would not sign with. v1.0.28+ use a
# keypair generated by `rsign` (that same crate), so the pty check below
# exercises the signer CI runs.
#
# Persisted state on Anton's Mac (do NOT re-ask):
#   ~/.config/skill-studio-release/minisign.key         (mode 0600, encrypted)
#   ~/.config/skill-studio-release/minisign.passphrase  (mode 0600)
#   ~/.config/skill-studio-release/minisign.pub         (RWRAKMUtAimeDjbhUiZU5OMP0tj7dOo3OPPy62n65bXLD94IdM1wk7DS)
#   ~/.cargo/bin/rsign                                  (cargo install rsign2)
# Source-of-truth note: Obsidian vault →
#   003 Resources/Technical Knowledge/Credentials-Secrets-Passwords/EasyChamp/
#     Skill Studio Desktop release credentials.md
#
# Runs on macOS /bin/bash 3.2. RELEASING.md describes the whole release flow.

set -euo pipefail

REPO="anton-abyzov/vskill"
REPO_URL="https://github.com/${REPO}.git"
MANIFEST_URL="https://verified-skill.com/desktop/latest.json"
KEY_DIR="${KEY_DIR:-${HOME}/.config/skill-studio-release}"
RSIGN="${RSIGN:-$(command -v rsign || echo "${HOME}/.cargo/bin/rsign")}"

usage() {
  echo "usage: $0 [<version>] [--dry-run] [--rotate-secrets] [--force]" >&2
}

DRY_RUN=0
ROTATE=0
FORCE=0
VERSION=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run) DRY_RUN=1 ;;
    --rotate-secrets) ROTATE=1 ;;
    --force) FORCE=1 ;;
    -h|--help) usage; exit 0 ;;
    -*) echo "unknown flag: $1" >&2; usage; exit 2 ;;
    *)
      if [[ -n "$VERSION" ]]; then echo "only one version allowed" >&2; usage; exit 2; fi
      VERSION="${1#desktop-}"
      VERSION="${VERSION#v}"
      ;;
  esac
  shift
done

die() { echo "ERROR: $*" >&2; exit 1; }
step() { echo ""; echo ">> $*"; }
ok() { echo "   OK: $*"; }
warn() { echo "   WARN: $*" >&2; }

WORK="$(mktemp -d)"
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT

MODE=""
[[ "$DRY_RUN" == 1 ]] && MODE=" (dry run)"

# ─── 1. Preflight (no side effects) ───────────────────────────────────────
step "[1/8] preflight${MODE}"
for tool in git gh curl python3; do
  command -v "$tool" >/dev/null || die "$tool not in PATH"
done
[[ -x "$RSIGN" ]] || die "rsign not found at $RSIGN (cargo install rsign2)"
gh auth status >/dev/null 2>&1 || die "gh is not authenticated (gh auth login)"
for f in minisign.key minisign.pub minisign.passphrase; do
  [[ -s "${KEY_DIR}/${f}" ]] || die "missing ${KEY_DIR}/${f}"
done
ok "tools, gh auth and key files"

# Version: compare against every desktop-v* tag on GitHub, not local tags.
git ls-remote --tags --refs "$REPO_URL" 'desktop-v*' > "$WORK/tags" \
  || die "git ls-remote $REPO_URL failed"
cat > "$WORK/version.py" <<'PY'
import re, sys
tags_file, wanted = sys.argv[1], sys.argv[2]
pat = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$")
def key(v):
    m = pat.match(v)
    if not m:
        return None
    # A final release sorts above its pre-releases.
    pre = m.group(4)
    return (int(m.group(1)), int(m.group(2)), int(m.group(3)), 1 if pre is None else 0, pre or "")
tags = []
for line in open(tags_file):
    parts = line.split()
    if parts and parts[-1].startswith("refs/tags/desktop-v"):
        tags.append(parts[-1][len("refs/tags/desktop-v"):])
known = sorted((t for t in tags if key(t)), key=key)
latest = known[-1] if known else ""
if not wanted:
    if not latest:
        sys.exit("no desktop-v* tag found; pass a version")
    m = pat.match(latest)
    a, b, c = int(m.group(1)), int(m.group(2)), int(m.group(3))
    # After 1.0.66-rc1 the default is 1.0.66, after 1.0.66 it is 1.0.67.
    wanted = "%d.%d.%d" % (a, b, c + 1 if m.group(4) is None else c)
if not key(wanted):
    sys.exit("version %s is not X.Y.Z or X.Y.Z-pre" % wanted)
if wanted in tags:
    sys.exit("desktop-v%s already exists on GitHub" % wanted)
if latest and key(wanted) <= key(latest):
    sys.exit("version %s is not newer than the newest tag desktop-v%s; roll back with desktop-rollback.yml" % (wanted, latest))
print(wanted + " " + (latest or "-"))
PY
VERSION_INFO="$(python3 "$WORK/version.py" "$WORK/tags" "$VERSION")" || die "version check failed (see above)"
VERSION="${VERSION_INFO%% *}"
PREVIOUS="${VERSION_INFO##* }"
TAG="desktop-v${VERSION}"
ok "version ${VERSION} (newest tag: desktop-v${PREVIOUS})"

# The commit to tag: main on GitHub, never the local checkout.
if [[ "$DRY_RUN" == 1 ]]; then
  SHA="$(git ls-remote "$REPO_URL" refs/heads/main | awk '{print $1}')"
else
  git fetch -q "$REPO_URL" main || die "git fetch $REPO_URL main failed"
  SHA="$(git rev-parse FETCH_HEAD)"
fi
[[ "$SHA" =~ ^[0-9a-f]{40}$ ]] || die "could not resolve main on $REPO_URL"
SUBJECT="$(gh api "repos/${REPO}/commits/${SHA}" -q '.commit.message | split("\n")[0]')" \
  || die "could not read commit ${SHA}"
ok "main is ${SHA:0:12} ${SUBJECT}"

# A dry-run push authenticates and compares refs but sends nothing, so HTTPS
# push credentials are proven before anything is tagged. The dry run has not
# fetched main, so it proves them with the local HEAD.
PUSH_SRC="$SHA"
[[ "$DRY_RUN" == 1 ]] && PUSH_SRC="HEAD"
git push --dry-run -q "$REPO_URL" "${PUSH_SRC}:refs/tags/${TAG}" \
  || die "git push --dry-run to ${REPO_URL} failed; check HTTPS git credentials (gh auth setup-git)"
ok "git can push ${TAG} to ${REPO_URL}"

# rsign is the Rust minisign crate tauri-bundler uses (BSD minisign keys are
# not interchangeable). It reads the password from a tty, so drive it through
# a pty. The passphrase is never printed, and rsign's output is discarded.
echo "release-desktop.sh check $(date +%s)" > "$WORK/check.txt"
if ! KEY_DIR="$KEY_DIR" RSIGN="$RSIGN" CHECK_FILE="$WORK/check.txt" python3 - <<'PY' >/dev/null
import os, pty, select, sys, time
kd = os.environ["KEY_DIR"]
with open(os.path.join(kd, "minisign.passphrase")) as f:
    pw = f.read().strip()
pid, fd = pty.fork()
if pid == 0:
    os.execv(os.environ["RSIGN"], ["rsign", "sign", "-s", os.path.join(kd, "minisign.key"), os.environ["CHECK_FILE"]])
sent, buf, deadline = False, b"", time.time() + 60
while True:
    left = deadline - time.time()
    if left <= 0:
        os.kill(pid, 9)
        os.waitpid(pid, 0)
        sys.stderr.write("rsign sign timed out\n")
        sys.exit(124)
    ready, _, _ = select.select([fd], [], [], left)
    if not ready:
        continue
    try:
        data = os.read(fd, 1024)
    except OSError:
        break
    if not data:
        break
    buf += data
    if not sent and b"assword" in buf:
        os.write(fd, (pw + "\n").encode())
        sent = True
_, status = os.waitpid(pid, 0)
code = os.WEXITSTATUS(status) if os.WIFEXITED(status) else 128 + os.WTERMSIG(status)
if code:
    sys.stderr.write("rsign sign exited %d\n" % code)
sys.exit(code)
PY
then
  die "rsign could not sign with ${KEY_DIR}/minisign.key (does minisign.passphrase unlock it?)"
fi
"$RSIGN" verify "$WORK/check.txt" -p "${KEY_DIR}/minisign.pub" -x "$WORK/check.txt.minisig" >/dev/null 2>&1 \
  || die "rsign signed, but the signature does not verify against ${KEY_DIR}/minisign.pub"
ok "minisign.key signs and minisign.pub verifies"

# Tauri expects plugins.updater.pubkey = base64(FULL minisign.pub file), not
# the raw key string. That mistake burned v1.0.13..v1.0.28 behind a misleading
# "Wrong password for that key" error. Check the file at the commit we tag.
EXPECTED_PUBKEY="$(base64 < "${KEY_DIR}/minisign.pub" | tr -d '\n\r\t ')"
gh api -H "Accept: application/vnd.github.raw" \
  "repos/${REPO}/contents/src-tauri/tauri.conf.json?ref=${SHA}" > "$WORK/tauri.conf.json" \
  || die "could not read src-tauri/tauri.conf.json at ${SHA}"
CONF_PUBKEY="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["plugins"]["updater"]["pubkey"])' "$WORK/tauri.conf.json")" \
  || die "src-tauri/tauri.conf.json at ${SHA:0:12} has no plugins.updater.pubkey"
if [[ "$CONF_PUBKEY" != "$EXPECTED_PUBKEY" ]]; then
  echo "ERROR: tauri.conf.json plugins.updater.pubkey at ${SHA:0:12} is not base64(${KEY_DIR}/minisign.pub)." >&2
  echo "  expected: ${EXPECTED_PUBKEY}" >&2
  echo "  found:    ${CONF_PUBKEY}" >&2
  exit 1
fi
ok "tauri.conf.json pubkey is base64(minisign.pub)"

gh secret list -R "$REPO" --json name -q '.[].name' > "$WORK/secrets" \
  || die "gh secret list -R $REPO failed"
MISSING=""
for s in TAURI_SIGNING_PRIVATE_KEY TAURI_SIGNING_PRIVATE_KEY_PASSWORD \
         APPLE_CERTIFICATE APPLE_CERTIFICATE_PASSWORD APPLE_SIGNING_IDENTITY \
         APPLE_ID APPLE_APP_SPECIFIC_PASSWORD APPLE_TEAM_ID \
         CLOUDFLARE_R2_ACCOUNT_ID CLOUDFLARE_R2_ACCESS_KEY_ID CLOUDFLARE_R2_SECRET_ACCESS_KEY \
         GPG_PRIVATE_KEY GPG_KEY_FPR; do
  grep -qx "$s" "$WORK/secrets" || MISSING="${MISSING} ${s}"
done
[[ -z "$MISSING" ]] || die "repo secrets missing:${MISSING}"
ok "release secrets exist (names only)"

# The newest decided main run of each canary. Cancelled and skipped runs say
# nothing about main, so look past them.
RED=0
DECIDED='select(.conclusion == "success" or .conclusion == "failure" or .conclusion == "timed_out" or .conclusion == "startup_failure")'
# canary <workflow file> <label> <jq filter on .event>
canary() {
  local wf="$1" label="$2" events="$3" line
  line="$(gh run list -R "$REPO" --workflow "$wf" --branch main --status completed --limit 30 \
    --json conclusion,event,url \
    -q '[.[] | select('"$events"') | '"$DECIDED"'][0] | select(. != null) | "\(.conclusion) \(.url)"')" \
    || die "gh run list --workflow $wf failed"
  if [[ -z "$line" ]]; then
    warn "$label has no completed run on main; nothing to check"
  elif [[ "${line%% *}" == "success" ]]; then
    ok "$label is green on main"
  else
    echo "   RED: $label on main: ${line}" >&2
    RED=1
  fi
}
canary notarize-dryrun.yml "notarize-dryrun.yml" '.event != "pull_request"'
# Its push runs skip the macOS notarize leg, so a green push run must not hide
# a red notarization: the newest scheduled or manual run has to be green too.
canary notarize-dryrun.yml "notarize-dryrun.yml full run (macOS included)" \
  '.event == "schedule" or .event == "workflow_dispatch"'
canary sidecar-smoke.yml "sidecar-smoke.yml" '.event != "pull_request"'
if [[ "$RED" == 1 ]]; then
  if [[ "$FORCE" == 1 ]]; then
    warn "tagging despite a red canary (--force)"
  elif [[ "$DRY_RUN" == 1 ]]; then
    warn "a real run stops here; pass --force to tag anyway"
  else
    die "a canary is red on main; fix it or pass --force"
  fi
fi

# ─── 2. Rotate the updater secrets (opt-in) ───────────────────────────────
if [[ "$ROTATE" == 1 ]]; then
  step "[2/8] rotating TAURI_SIGNING_PRIVATE_KEY + TAURI_SIGNING_PRIVATE_KEY_PASSWORD"
  if [[ "$DRY_RUN" == 1 ]]; then
    echo "   [dry-run] would gh secret set both from ${KEY_DIR}"
  else
    base64 < "${KEY_DIR}/minisign.key" | tr -d '\n\r\t ' \
      | gh secret set TAURI_SIGNING_PRIVATE_KEY --repo "$REPO" >/dev/null
    tr -d '\n\r' < "${KEY_DIR}/minisign.passphrase" \
      | gh secret set TAURI_SIGNING_PRIVATE_KEY_PASSWORD --repo "$REPO" >/dev/null
    ok "secrets uploaded"
  fi
else
  step "[2/8] secrets unchanged (--rotate-secrets re-uploads them)"
fi

read_manifest() {
  # $1 = output file. Prints "<x-manifest-source> <version>".
  local out="$1" src
  src="$(curl -fsS -D - -o "$out" "${MANIFEST_URL}?ts=$(date +%s)" \
    | tr -d '\r' | awk -F': ' 'tolower($1)=="x-manifest-source"{print $2}')" || return 1
  python3 -c 'import json,sys; print(sys.argv[2] + " " + str(json.load(open(sys.argv[1])).get("version", "?")))' \
    "$out" "${src:-?}"
}

verify_bundle_signature() {
  # $1 = manifest file. Downloads its darwin-aarch64 bundle and checks the
  # manifest's signature for it with rsign against minisign.pub.
  python3 - "$1" "$WORK/bundle.sig" "$WORK/bundle.url" <<'PY' || return 1
import base64, json, sys, urllib.parse
p = json.load(open(sys.argv[1]))["platforms"]["darwin-aarch64"]
with open(sys.argv[2], "wb") as f:
    f.write(base64.b64decode(p["signature"]))
# Live URLs contain spaces ("Skill Studio.app.tar.gz").
with open(sys.argv[3], "w") as f:
    f.write(urllib.parse.quote(p["url"], safe=":/?&=%~"))
PY
  local url
  url="$(cat "$WORK/bundle.url")"
  curl -fsSL --retry 3 -o "$WORK/bundle" "$url" || return 1
  "$RSIGN" verify "$WORK/bundle" -p "${KEY_DIR}/minisign.pub" -x "$WORK/bundle.sig" >/dev/null || return 1
  ok "${url} verifies against minisign.pub"
}

# ─── Dry run: the plan + read-only checks of the live release ─────────────
if [[ "$DRY_RUN" == 1 ]]; then
  step "[3/8] [dry-run] would push ${SHA:0:12} as ${TAG} to ${REPO_URL}"
  echo "   then watch desktop-release.yml for ${TAG}, check the release assets,"
  echo "   require ${MANIFEST_URL} to serve ${VERSION} from r2, verify the"
  echo "   darwin-aarch64 signature, and promote the release if it is a draft."
  step "[dry-run] read-only check of the live release"
  LIVE="$(read_manifest "$WORK/latest.json")" || die "could not read ${MANIFEST_URL}"
  echo "   live manifest: version ${LIVE##* }, source ${LIVE%% *}"
  verify_bundle_signature "$WORK/latest.json" \
    || die "the live darwin-aarch64 bundle does not verify against minisign.pub"
  echo ""
  echo "Dry run complete: nothing was tagged, pushed or changed."
  exit 0
fi

# ─── 3. Tag main + push the tag ───────────────────────────────────────────
step "[3/8] tagging ${SHA:0:12} as ${TAG}"
# Push the commit straight to refs/tags, so a stale local tag cannot be used.
git push -q "$REPO_URL" "${SHA}:refs/tags/${TAG}" || die "could not push ${TAG}"
ok "pushed ${TAG}"

# ─── 4. Watch CI ──────────────────────────────────────────────────────────
step "[4/8] waiting for the Desktop Release run"
RUN_ID=""
for _ in $(seq 1 24); do
  RUN_ID="$(gh run list -R "$REPO" --workflow desktop-release.yml --branch "$TAG" --event push \
    --json databaseId -q '.[0].databaseId')" || RUN_ID=""
  [[ -n "$RUN_ID" ]] && break
  sleep 5
done
[[ -n "$RUN_ID" ]] || die "no desktop-release.yml run for ${TAG} after 120s"
RUN_URL="https://github.com/${REPO}/actions/runs/${RUN_ID}"
echo "   run: ${RUN_URL}"
gh run watch "$RUN_ID" -R "$REPO" --exit-status --interval 15 || die "Desktop Release failed: ${RUN_URL}"
ok "CI green"

# ─── 5. Release assets ────────────────────────────────────────────────────
step "[5/8] checking release assets"
gh release view "$TAG" -R "$REPO" --json assets -q '.assets[].name' > "$WORK/assets" \
  || die "gh release view ${TAG} failed"
for pattern in '\.dmg$' '\.app\.tar\.gz$' '\.app\.tar\.gz\.sig$' '\.msi$' 'x64-setup\.exe\.sig$' \
               '\.deb$' '\.rpm$' '\.AppImage$' '\.AppImage\.sig$'; do
  grep -qE "$pattern" "$WORK/assets" || die "release ${TAG} has no asset matching ${pattern}"
done
ok "bundles and updater signatures attached"

# ─── 6. Live manifest (served from R2) ────────────────────────────────────
step "[6/8] reading ${MANIFEST_URL}"
LIVE=""
for _ in 1 2 3 4 5 6; do
  if LIVE="$(read_manifest "$WORK/latest.json")" && [[ "$LIVE" == "r2 ${VERSION}" ]]; then
    break
  fi
  sleep 10
done
[[ "$LIVE" == "r2 ${VERSION}" ]] \
  || die "live manifest reads '${LIVE:-unreadable}' (source version); expected 'r2 ${VERSION}'"
python3 - "$WORK/latest.json" <<'PY' || die "latest.json is missing a platform"
import json, sys
p = json.load(open(sys.argv[1]))["platforms"]
missing = [k for k in ("darwin-aarch64", "windows-x86_64", "linux-x86_64") if k not in p]
if missing:
    sys.exit("missing: " + ", ".join(missing))
PY
ok "latest.json serves ${VERSION} from R2 with all three platforms"

# ─── 7. Updater signature of the shipped macOS bundle ─────────────────────
step "[7/8] verifying the darwin-aarch64 updater signature"
verify_bundle_signature "$WORK/latest.json" \
  || die "the darwin-aarch64 bundle in latest.json does not verify against minisign.pub"

# ─── 8. Promote + stale drafts ────────────────────────────────────────────
step "[8/8] promoting the release + removing stale drafts"
IS_DRAFT="$(gh release view "$TAG" -R "$REPO" --json isDraft -q .isDraft)" \
  || die "gh release view ${TAG} failed"
if [[ "$IS_DRAFT" == "true" ]]; then
  gh release edit "$TAG" --draft=false -R "$REPO" >/dev/null || die "could not promote ${TAG}"
  ok "promoted ${TAG}"
else
  ok "${TAG} is already published"
fi
gh release list -R "$REPO" --limit 100 --json tagName,isDraft \
  -q '.[] | select(.isDraft == true) | select(.tagName | startswith("desktop-v")) | .tagName' > "$WORK/drafts" \
  || die "gh release list failed"
while read -r t; do
  [[ -z "$t" || "$t" == "$TAG" ]] && continue
  # The release only: its git tag stays (no --cleanup-tag).
  if gh release delete "$t" -R "$REPO" -y >/dev/null; then
    ok "deleted stale draft ${t}"
  else
    warn "could not delete stale draft ${t}"
  fi
done < "$WORK/drafts"

echo ""
echo "DESKTOP RELEASE ${VERSION} LIVE"
echo "  GitHub:   https://github.com/${REPO}/releases/tag/${TAG}"
echo "  Manifest: ${MANIFEST_URL}"
echo "  Page:     https://verified-skill.com/desktop"
